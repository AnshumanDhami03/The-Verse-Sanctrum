// Helper function to convert number to Roman numeral
function toRoman(num) {
  const romanNumerals = [
    ['XL', 40], ['X', 10], ['IX', 9], ['V', 5], ['IV', 4], ['I', 1]
  ]
  let result = ''
  for (const [roman, value] of romanNumerals) {
    while (num >= value) {
      result += roman
      num -= value
    }
  }
  return result
}
 
